#!/usr/bin/env bash
set -euo pipefail

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
passes=0
for text in 'Useful change' 'Body with ordinary prose' 'Refs: #26'; do
  printf '%s\n' "$text" > "$work/body"
  bash "$root/scripts/check-codex-attribution.sh" "$work/body" >/dev/null
  passes=$((passes + 1))
done
for text in 'Co-Authored-By: Agent <agent@example.invalid>' 'Agent-Session: value' 'Codex-Session: value' 'Generated with Codex' 'Generated by OpenAI' 'https://example.invalid/code/session_example' 'https://chatgpt.com/codex/tasks/example'; do
  printf '%s\n' "$text" > "$work/body"
  code=0
  bash "$root/scripts/check-codex-attribution.sh" "$work/body" >/dev/null 2>&1 || code=$?
  [ "$code" -eq 2 ] || { printf 'FAIL attribution negative control\n'; exit 1; }
  passes=$((passes + 1))
done
code=0
bash "$root/scripts/check-codex-attribution.sh" "$work/absent" >/dev/null 2>&1 || code=$?
[ "$code" -eq 1 ] || exit 1
passes=$((passes + 1))
printf 'PASS %s Codex attribution checks\n' "$passes"
